// Token Radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// 160 strongest pre-token protocols outside it, chosen by this model's own score. A protocol is
// pre-token when its record carries no token (no market cap, no CoinGecko id, no symbol). Protocols
// whose token already trades are kept apart in the Live view and shown at their market cap, never
// mixed into the ranked board. A protocol is rankable when it is pre-token and is not a centralised
// exchange, a liquid staking or restaking product, or a restaked-BTC product, and its name carries no
// version marker, no whole word wrapped, staked or staking, and no exchange's name up front: those
// are products of a token that already trades, or a pool of another protocol, not a launch of their
// own. A bridge counts only when it is small bridge infrastructure: its name ends in "bridge" and
// its TVL sits below the watchlist floor. That keeps out the wrapped assets the house names (WBTC,
// USDT0) and the big chain bridges (Base Bridge, CCIP), which are not launches of their own, while a
// small chain bridge still counts as the early radar it is. Bridges earn the lowest multiple:
// bridging is thin-margin infrastructure.
//
// Implied value follows only from the snapshot's own figures:
//
//   catMult    = CATEGORY_MULTIPLE[category] (a table over the snapshot's category field, default 0.22)
//   growth     = clamp(change_7d, -70, 150) per cent (unreported: 0)
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.65 + 0.35 x min(age_days, 1095) / 1095   (age_days unknown: 365)
//   chainMult  = 1 + 0.04 x min(chains - 1, 5)              (one chain: 1.00, six or more: 1.20)
//   implied    = max(1, round(tvl_usd x catMult x growthMult x maturityMult x chainMult))
//
// A dollar of TVL is worth more in a business whose token captures the flow (a DEX, a lender) than in
// one that only moves it (a bridge). Growth rewards momentum, age rewards a record built with no token
// yet, and breadth across chains rewards reach. No protocol name is ever special-cased: the same
// function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

